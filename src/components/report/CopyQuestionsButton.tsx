"use client";

import React, { useState } from "react";
import { Copy, Check } from "lucide-react";
import { Button } from "../ui/Button";
import type { CustomerDiscoveryQuestions } from "@/types";

interface CopyQuestionsButtonProps {
  discoveryData: CustomerDiscoveryQuestions;
}

export function CopyQuestionsButton({ discoveryData }: CopyQuestionsButtonProps) {
  const [copied, setCopied] = useState(false);

  const handleCopy = async () => {
    let script = `CUSTOMER DISCOVERY INTERVIEW SCRIPT (THE MOM TEST METHODOLOGY)\n`;
    script += `Generated by FounderFlow AI\n`;
    script += `Notice: Ask about past life and behavior. Never pitch the product or ask hypothetical questions.\n\n`;

    (discoveryData.themes || []).forEach((theme, tIdx) => {
      script += `==============================================\n`;
      script += `SECTION ${tIdx + 1}: ${theme.theme.toUpperCase()}\n`;
      script += `Goal: ${theme.description}\n`;
      script += `==============================================\n\n`;

      (theme.questions || []).forEach((q, qIdx) => {
        script += `Q${qIdx + 1}: "${q.question}"\n`;
        script += `   • Hypothesis tested: ${q.purpose}\n`;
        script += `   • Follow-up probe: ${q.followUpHint}\n\n`;
      });
    });

    if (discoveryData.interviewTips && discoveryData.interviewTips.length > 0) {
      script += `\nINTERVIEW TIPS:\n`;
      discoveryData.interviewTips.forEach((tip) => {
        script += `- ${tip}\n`;
      });
    }

    try {
      await navigator.clipboard.writeText(script);
      setCopied(true);
      setTimeout(() => setCopied(false), 2500);
    } catch (err) {
      console.error("Failed to copy script:", err);
    }
  };

  return (
    <Button
      variant="outline"
      size="sm"
      onClick={handleCopy}
      className="space-x-1.5 text-xs border-indigo-200 dark:border-indigo-900/50 hover:bg-indigo-50 dark:hover:bg-indigo-950/30 text-indigo-600 dark:text-indigo-400 font-medium"
    >
      {copied ? (
        <>
          <Check className="w-3.5 h-3.5 text-emerald-500" />
          <span className="text-emerald-600 dark:text-emerald-400">Copied to Clipboard!</span>
        </>
      ) : (
        <>
          <Copy className="w-3.5 h-3.5" />
          <span>Copy Interview Script</span>
        </>
      )}
    </Button>
  );
}

